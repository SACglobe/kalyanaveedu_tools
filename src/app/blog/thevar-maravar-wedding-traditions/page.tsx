  <li><strong>அஞ்சுகம் அம்மையார் நினைவு கலப்புத் திருமண நிதியுதவித் திட்டம்:</strong> சாதி மறுப்புத் திருமணம் செய்து கொள்ளும் தம்பதியருக்கு வழங்​கப்படும் உதவி.</li>
